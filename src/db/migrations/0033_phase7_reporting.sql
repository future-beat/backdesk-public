-- NOT constrained, deliberately: `monthly_reports.figures`, `.lines`,
-- `.baseline`, `.constants` and `.fees`. They are frozen DOCUMENTS, and their
-- shape is versioned by the generator that wrote them — a CHECK on jsonb keys
-- would make an old report unreadable the first time the report gains a figure,
-- which is the opposite of what freezing them is for. `NOT NULL` is the whole
-- database-level guarantee here, and it is the one that matters: a report
-- missing any of the five cannot be re-read as the thing that was sent.

-- ── TABLE PRIVILEGES (WR-04, following 0005/0007/0011/0017/0032) ────────────
--
-- EVERY NEW TABLE NEEDS ITS OWN BLOCK. 0003 said it, 0005 explained why saying
-- it once was not enough, and 0007, 0011, 0017 and 0032 each repeated it. Recap:
--
--   RLS decides WHICH ROWS a role may see. Table privileges decide whether the
--   role may touch the table at all. Postgres checks privileges FIRST, so a
--   table with a perfect policy and no GRANT returns `42501 permission denied`
--   — an ERROR, not an empty result — which leaks the table's existence and
--   breaks the property that denial and absence are indistinguishable.
--
-- REVOKE-THEN-GRANT, because hosted Supabase installs ALTER DEFAULT PRIVILEGES
-- at bootstrap and silently hands anon and authenticated the full set —
-- SELECT, INSERT, UPDATE, DELETE, TRUNCATE — on every table drizzle creates in
-- `public`. A fresh `supabase start` database (what CI runs) has no such
-- default, so skipping the REVOKE makes CI and production disagree with
-- production being the permissive one. TRUNCATE is why this is not merely
-- untidy: TRUNCATE IS NOT SUBJECT TO ROW-LEVEL SECURITY, so no policy test
-- could ever catch it.
--
-- These three tables are the phase's whole reason to be careful here: they are
-- what the client is BILLED from. T-7-01.

REVOKE ALL ON public.quote_attributions FROM anon;
--> statement-breakpoint
