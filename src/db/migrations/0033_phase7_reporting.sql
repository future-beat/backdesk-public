-- quote_attributions: EVIDENCE, and read-only to `authenticated` because A
-- CONSOLE-WRITTEN ROW IS FABRICATED BILLED REVENUE.
--
-- An INSERT grant invents a recovered job the client is then invoiced for and
-- asked to verify against their own ServiceM8 account — the single most
-- damaging row this system could contain. An UPDATE grant edits `gross_cents`
-- or `conservative_cents` after the fact, which is the same thing with a
-- shorter audit trail. A DELETE grant removes the row that CONSUMED the D-04
-- never-twice claim, so the next replayed `won` event attributes the same job a
-- second time and the client is billed twice for one win.
--
-- anon keeps SELECT so an unauthenticated read returns `[]` rather than 42501;
-- RLS then returns zero rows.
GRANT SELECT ON public.quote_attributions TO anon;
--> statement-breakpoint
GRANT SELECT ON public.quote_attributions TO authenticated;
--> statement-breakpoint
GRANT ALL ON public.quote_attributions TO service_role;
--> statement-breakpoint

-- monthly_reports: FROZEN, and read-only to `authenticated` because A CONSOLE
-- UPDATE REWRITES A DOCUMENT A CLIENT WAS ALREADY SENT.
--
-- The entire value of D-11 is that the PDF stapled to an invoice is reproducible
-- months later. An UPDATE grant makes the row and the document diverge with no
-- trace, and a report that can be edited afterwards is not evidence of anything.
-- A DELETE grant erases the record of what was claimed — including the version
-- history that lets us say "here is what we sent you, and here is the corrected
-- one". An INSERT grant would let a caller supply its own `version` and
-- `generated_at`, and the version sequence is the arbiter, not a suggestion.
--
-- A CORRECTION IS A NEW VERSION, written by the service-role action. There is
-- no update path in the repository and none here.
GRANT SELECT ON public.monthly_reports TO anon;
--> statement-breakpoint
GRANT SELECT ON public.monthly_reports TO authenticated;
--> statement-breakpoint
GRANT ALL ON public.monthly_reports TO service_role;
--> statement-breakpoint

-- tenant_fees: APPEND-ONLY, and read-only to `authenticated` because A CONSOLE
-- EDIT REWRITES THE DENOMINATOR OF A MULTIPLE ALREADY REPORTED.
--
-- The `tenant_attestations` posture, for a billing reason. Lowering an
-- `amount_cents` after a report has quoted a multiple against it changes what
-- the client was told they got for their money, retroactively and invisibly. A
