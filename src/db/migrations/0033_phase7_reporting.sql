-- ── CLOSED VOCABULARIES (WR-03, following 0004, 0008, 0011, 0017, 0032) ─────
--
-- `authenticated` holds no write grant on any of these tables, so these CHECKs
-- are not defending against a curl with an operator JWT. THEY DEFEND AGAINST
-- US: the service-role attribution consumer and the service-role fee action are
-- the only writers, and the TypeScript unions in src/db/schema/*.ts erase before
-- the INSERT is built.
--
-- IDEMPOTENT BY CONSTRUCTION (0004's pattern): Postgres has no
-- ADD CONSTRAINT IF NOT EXISTS, so drop-if-present then re-add.

-- A zero-dollar attribution and an attribution whose dollar figure we could not
-- read are DIFFERENT FACTS with different operator responses, and a bare
-- `gross_cents = 0` cannot tell them apart. `'missing'` is what the report reads
-- to render "value unavailable — check this job in ServiceM8" instead of a $0
-- line the client would (rightly) query. A typo here inserts cleanly and turns
-- an honest gap into a silent zero on an invoice.
ALTER TABLE public.quote_attributions DROP CONSTRAINT IF EXISTS quote_attributions_value_source_known;
--> statement-breakpoint
ALTER TABLE public.quote_attributions
  ADD CONSTRAINT quote_attributions_value_source_known
  CHECK (value_source IN ('mirror','missing'));
--> statement-breakpoint

-- `'connect'` is the client's OWN measured pre-service win rate; `'default'` is
-- the published fallback for a client with too little history to measure one
-- (D-08). The report's methodology footnote prints one sentence or the other,
