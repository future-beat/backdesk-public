-- NOT constrained, deliberately: `escalations.outcome`. It follows the
-- send_ledger rule one table over — NULL means "claimed, outcome unknown" — and
-- the values are derived from a third party's response on a path that is
-- LOW-confidence research. A CHECK here would turn a provider adding a status
-- into a 23514 raised inside the tick that is trying to tell a tradie about a
-- hot lead. The mapping is closed in TypeScript (ESCALATION_OUTCOMES).

-- ── TABLE PRIVILEGES (WR-04, following 0005/0007/0011/0017) ─────────────────
--
-- EVERY NEW TABLE NEEDS ITS OWN BLOCK. 0003 said it, 0005 explained why saying
-- it once was not enough, and 0007, 0011 and 0017 each repeated it. Recap:
--
--   RLS decides WHICH ROWS a role may see. Table privileges decide whether the
--   role may touch the table at all. Postgres checks privileges FIRST, so a
--   table with a perfect policy and no GRANT returns `42501 permission denied`
--   — an ERROR, not an empty result — which leaks the table's existence and
--   breaks the property that denial and absence are indistinguishable.
--
-- REVOKE-THEN-GRANT, because hosted Supabase installs ALTER DEFAULT PRIVILEGES
-- at bootstrap and silently hands anon and authenticated the full set —
-- SELECT, INSERT, UPDATE, DELETE, TRUNCATE — on every table drizzle creates in
-- `public`. A fresh `supabase start` database (what CI runs) has no such
-- default, so skipping the REVOKE makes CI and production disagree with
-- production being the permissive one. TRUNCATE is why this is not merely
-- untidy: TRUNCATE IS NOT SUBJECT TO ROW-LEVEL SECURITY, so no policy test
-- could ever catch it.

REVOKE ALL ON public.escalations FROM anon;
--> statement-breakpoint
REVOKE ALL ON public.escalations FROM authenticated;
--> statement-breakpoint
REVOKE ALL ON public.tenant_attestations FROM anon;
--> statement-breakpoint
REVOKE ALL ON public.tenant_attestations FROM authenticated;
--> statement-breakpoint

-- escalations: EVIDENCE, and read-only to `authenticated` for the same reason
-- `send_ledger` and `inbound_messages` are.
--
-- This table IS the D-08 never-twice claim. A DELETE grant removes the row that
-- proves a tradie was already told about a reply — and the next tick would then
-- text them again about the same customer, which is the noise that teaches them
-- to ignore the next alert. An INSERT grant fabricates an escalation Phase 7
-- reports a response time against; an UPDATE grant rewrites `outcome`, turning
-- "we do not know whether this reached them" into a definite answer nobody
-- verified.
--
-- anon keeps SELECT so an unauthenticated read returns `[]` rather than 42501;
-- RLS then returns zero rows.
GRANT SELECT ON public.escalations TO anon;
--> statement-breakpoint
GRANT SELECT ON public.escalations TO authenticated;
--> statement-breakpoint
GRANT ALL ON public.escalations TO service_role;
--> statement-breakpoint

-- tenant_attestations: APPEND-ONLY, and the absent UPDATE is the one that
-- matters (the suppressed_contacts posture, for a different reason).
--
-- A row here records that a named human looked at a client's ServiceM8 settings
-- at a recorded moment and wrote down what they saw. An UPDATE grant makes that
-- editable after the fact, which means the attestation that was made and the
-- attestation that is recorded could differ with no trace — and an attestation
-- that can be edited afterwards is not evidence of anything. A DELETE grant
-- erases the staleness history D-15's re-check policy reads. An INSERT grant
-- would let a caller supply their own `attested_at`, and the whole value of the
-- row is that the moment is OURS.
--
-- Re-attestation is a NEW ROW, written by the service-role action. There is no
-- update path in the repository and none here.
GRANT SELECT ON public.tenant_attestations TO anon;
